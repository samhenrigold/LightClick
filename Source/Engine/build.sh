#!/bin/zsh
# Usage: build.sh [debug|release]. Builds the EL1 monitor blob, the x86 test images, the Swift package, and signs the tools.
set -eu
here=${0:A:h}
config=${1:-release}
gen=$here/Sources/CEngine/generated
out=$here/.build/images
mkdir -p "$gen" "$out"

# ---- Monitor: freestanding arm64, linked at its private VA ----
cc=(clang -target arm64-apple-macos13 -O2 -ffreestanding -fno-builtin -fno-stack-protector -mgeneral-regs-only
    -fno-unwind-tables -fno-asynchronous-unwind-tables -ffixed-x18 -Wall -Wextra -Wno-unused-function
    -I"$here/Sources/CEngine/include")
"${cc[@]}" -c "$here/Monitor/monitor.c" -o "$out/monitor.o"
clang -target arm64-apple-macos13 -march=armv8.5-a+crc -c "$here/Monitor/vectors.s" -o "$out/vectors.o"
ld -arch arm64 -preload -e _mon_init -no_uuid -pagezero_size 0 \
    -segaddr __TEXT 0xF00000000000 -segaddr __DATA 0xF00000200000 -segaddr __EL0 0xF00000400000 \
    -o "$out/monitor.macho" "$out/vectors.o" "$out/monitor.o"
{
    echo '// Generated by build.sh from Monitor/. Do not edit.'
    echo '#include "monitor_blob.h"'
    echo 'static const unsigned char blob[] = {'
    xxd -i < "$out/monitor.macho"
    echo '};'
    echo 'const unsigned char *engine_monitor_macho_ptr(void) { return blob; }'
    echo 'long engine_monitor_macho_size(void) { return sizeof blob; }'
    for sym in mon_init mon_vectors mon_enter_guest; do
        addr=$(nm "$out/monitor.macho" | awk -v s="_$sym" '$3 == s { print $1 }')
        echo "const unsigned long long engine_sym_$sym = 0x$addr;"
    done
} > "$gen/monitor_blob.c"

# ---- x86 test images and comparison runners ----
"$here/Tests/x86/build-images.sh" "$out"

# ---- Swift package ----
cd "$here"
swift build -c "$config" --product engine-run 2>&1 | grep -E "error|warning: unre|Compiling engine|Build complete|: error" | head -40 || true
codesign --force --sign - --entitlements "$here/Engine.entitlements" "$here/.build/$config/engine-run"
